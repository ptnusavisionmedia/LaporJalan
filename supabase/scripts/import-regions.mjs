#!/usr/bin/env node
// Converts an official region list (Kemendagri codes) into an idempotent SQL file.
//
//   node supabase/scripts/import-regions.mjs wilayah.csv > supabase/regions-import.sql
//
// Input: CSV/TSV lines of `code,name` (header line optional), e.g.
//   32.73,Kota Bandung
//   32.73.01,Sukasari
//   32.73.01.1001,Gegerkalong
// Level and parent are derived from the code. No data is bundled: obtain the list from the
// official Kemendagri/BPS publication and check its licence before redistributing it.
import { readFileSync } from 'node:fs';

const CODE = /^[0-9]{2}(\.[0-9]{2}(\.[0-9]{2}(\.[0-9]{4})?)?)?$/;
const file = process.argv[2];
if (!file) {
  console.error('Usage: import-regions.mjs <file.csv>');
  process.exit(1);
}

const rows = new Map();
const errors = [];
readFileSync(file, 'utf8')
  .split(/\r?\n/)
  .forEach((line, i) => {
    if (!line.trim()) return;
    const m = line.match(/^\s*"?([^",\t]+)"?\s*[,\t](.*)$/);
    if (!m) return errors.push(`baris ${i + 1}: format tidak dikenali`);
    const code = m[1].trim();
    let name = m[2].trim();
    // standard CSV: strip quotes only when they wrap the whole field; "" is a literal quote
    if (name.length >= 2 && name.startsWith('"') && name.endsWith('"')) {
      name = name.slice(1, -1).replace(/""/g, '"');
    }
    if (i === 0 && !CODE.test(code)) return; // header
    if (!CODE.test(code)) return errors.push(`baris ${i + 1}: kode tidak valid "${code}"`);
    if (!name.trim()) return errors.push(`baris ${i + 1}: nama kosong`);
    if (rows.has(code)) return errors.push(`baris ${i + 1}: kode ganda "${code}"`);
    rows.set(code, name.trim());
  });

const levelOf = (c) => c.split('.').length;
const parentOf = (c) => (levelOf(c) === 1 ? null : c.split('.').slice(0, -1).join('.'));

// A child may reference a province from seed.sql, so only deeper parents must be in the file.
for (const code of rows.keys()) {
  const p = parentOf(code);
  if (p && levelOf(p) > 1 && !rows.has(p)) errors.push(`induk "${p}" untuk "${code}" tidak ada di berkas`);
}
if (errors.length) {
  console.error(errors.slice(0, 50).join('\n'));
  if (errors.length > 50) console.error(`... dan ${errors.length - 50} kesalahan lain`);
  process.exit(1);
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const sorted = [...rows].sort(([a], [b]) => levelOf(a) - levelOf(b) || a.localeCompare(b));
const out = ['-- generated by supabase/scripts/import-regions.mjs', 'begin;'];
for (let i = 0; i < sorted.length; i += 500) {
  const values = sorted
    .slice(i, i + 500)
    .map(([c, n]) => `(${q(c)}, ${q(n)}, ${levelOf(c)}, ${parentOf(c) ? q(parentOf(c)) : 'null'})`);
  out.push(
    'insert into public.regions (code, name, level, parent_code) values\n  ' +
      values.join(',\n  ') +
      '\non conflict (code) do update set name = excluded.name, level = excluded.level, parent_code = excluded.parent_code;',
  );
}
out.push('commit;');
console.log(out.join('\n'));
console.error(`OK: ${rows.size} wilayah`);
